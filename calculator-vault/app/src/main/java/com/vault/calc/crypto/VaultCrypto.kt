package com.vault.calc.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.io.File
import java.io.InputStream
import java.io.OutputStream
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.CipherInputStream
import javax.crypto.CipherOutputStream
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * File encryption for the vault.
 *
 * Every stored blob is encrypted with AES-256-GCM using a key held in the
 * Android Keystore (it never leaves secure hardware where available). The 12-byte
 * IV is random per file and written as a header in front of the ciphertext.
 *
 * Streaming is used so large photos/videos are never fully loaded into memory.
 */
object VaultCrypto {

    private const val KEYSTORE = "AndroidKeyStore"
    private const val KEY_ALIAS = "vault_master_key"
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val IV_SIZE = 12
    private const val TAG_BITS = 128

    fun ensureKey(): SecretKey {
        val ks = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        (ks.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let {
            return it.secretKey
        }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build()
        generator.init(spec)
        return generator.generateKey()
    }

    /** Encrypts [input] into [target]. The IV is written as the file header. */
    fun encrypt(input: InputStream, target: File) {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, ensureKey())
        val iv = cipher.iv // 12 bytes, generated by the provider
        target.outputStream().use { fileOut ->
            fileOut.write(iv)
            CipherOutputStream(fileOut, cipher).use { cipherOut ->
                input.copyTo(cipherOut, bufferSize = 64 * 1024)
            }
        }
    }

    /** Decrypts [source] and writes the plaintext to [out]. [out] is not closed. */
    fun decryptTo(source: File, out: OutputStream) {
        openDecryptStream(source).use { it.copyTo(out, bufferSize = 64 * 1024) }
    }

    fun decryptToBytes(source: File): ByteArray =
        openDecryptStream(source).use { it.readBytes() }

    /** Returns a stream of the decrypted contents of [source]. Caller must close it. */
    fun openDecryptStream(source: File): InputStream {
        val fileIn = source.inputStream()
        val iv = ByteArray(IV_SIZE)
        var read = 0
        while (read < IV_SIZE) {
            val r = fileIn.read(iv, read, IV_SIZE - read)
            if (r < 0) { fileIn.close(); error("Corrupt vault file: missing IV") }
            read += r
        }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, ensureKey(), GCMParameterSpec(TAG_BITS, iv))
        return CipherInputStream(fileIn, cipher)
    }
}
